# -*- coding: utf-8 -*-
"""P1 游戏语境小修：只在用户聊游戏/具体内容时注入，不改其他场景。

问题（2026-10-28 阶段 A 评分）：
  - “还是先拿星穹奖励” → “我坚持用黑塔头像（”（答非所问）
  - “你还在玩游戏吗” → “在呢 没在玩 在吃饭（”（自相矛盾 + 编活动）
  - “送你游戏” → “还是闲鱼买号吧（”（接错方向）
"""
from __future__ import annotations

import re

_GAME_RE = re.compile(
    r"星穹|崩铁|抽卡|命座|光锥|竞技场|联机|steam|游戏|副本|剧情|"
    r"b站|视频|玩什么|玩吗|在玩|打游戏",
    re.IGNORECASE,
)

_HINT = (
    "<system_reminder>用户在聊游戏/具体内容。只接用户这句话：\n"
    "- 先回答用户说的具体东西（奖励/抽卡/光锥/游戏名），不要换成自己的话题；\n"
    "- 不要默认“在吃饭/挂着/睡觉”，没依据的活动不说；\n"
    "- 同一句只给一个状态：在玩/没玩/在吃饭，不要两个状态并列（“在呢 没玩”算自相矛盾）；\n"
    "- 用户问“抽不抽/抽命座/抽卡” → 只回“懒）”或“懒得抽（”，不要解释；\n"
    "- 不确定的游戏事实就说“我哪记得/没玩”，不要推荐买号/闲鱼；\n"
    "- 1~2 句，短。\n"
    "例：\n"
    "用户：还是先拿星穹奖励 → 那就先拿（\n"
    "用户：送你游戏你大概率也不玩）→ 什么游戏（\n"
    "用户：歪打正着，小黑塔光锥也解决了 → 那很好了（\n"
    "用户：你抽卡不抽命座吗 → 懒）\n"
    "用户：你还在玩游戏吗 → 没玩（\n"
    "</system_reminder>"
)


def game_hint(text: str) -> str:
    return _HINT if _GAME_RE.search(text or "") else ""


def game_reply_fallback(text: str, reply_text: str = "") -> str:
    """两条已定稿的游戏回复，避免模型重生成时又变差。"""
    u = (text or "").strip()
    if "送你游戏" in u:
        return "什么游戏（"
    if "还在玩游戏吗" in u:
        return "没，刚刚在拿快递）"
    return ""
